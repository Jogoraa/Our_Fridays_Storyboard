"""Write COSTS.md from runs.jsonl and the output metadata. Run: `uv run python -m pipeline.costs`.

Nothing here is estimated by hand: latencies and GPU seconds come from the run log, audio lengths
from the files' metadata. List prices are the only outside numbers and are named with their source.
"""
from __future__ import annotations

import json
import statistics
from collections import defaultdict

from pipeline.common import OUTPUTS, ROOT, RUNS_PATH

# List prices, read on 2026-11-25.
# Gemini: https://aistudio.google.com/docs/pricing ("Equivalent to ... per 10s audio", paid tier, through 31 Dec 2026).
SPEECH_USD_PER_10S = {"gemini-3.8-flash-tts": 0.00225, "gemini-3.8-flash-lite-tts": 0.0015}
# Google Cloud on-demand price for one NVIDIA T4, us-central1. Kaggle gives two T4s; a job uses one.
T4_USD_PER_HOUR = 0.35


def _rows() -> list[dict]:
    return [json.loads(line) for line in RUNS_PATH.read_text(encoding="utf-8").splitlines() if line.strip()]


def _audio_seconds_by_model() -> dict[str, float]:
    """Seconds of narration that were kept, by the model that voiced them (current film and archive)."""
    totals: dict[str, float] = defaultdict(float)
    for meta in OUTPUTS.rglob("*.wav.meta.json"):
        record = json.loads(meta.read_text(encoding="utf-8"))
        if record.get("model") and record.get("seconds"):
            totals[record["model"]] += float(record["seconds"])
    return totals


def build() -> str:
    rows = _rows()
    groups: dict[tuple, list[dict]] = defaultdict(list)
    for row in rows:
        groups[(row["stage"], row["provider"], row["model"])].append(row)

    lines = [
        "# Costs and measurements",
        "",
        "Generated by `uv run python -m pipeline.costs` from `runs.jsonl` and the metadata beside each output.",
        "Money spent: **0 USD**. Every model ran on a free tier or a free GPU.",
        "",
        f"Log covered: {len(rows)} model-call attempts, {rows[0]['ts']} to {max(r['ts'] for r in rows)} (UTC).",
        "",
        "## Calls and latency per stage and model",
        "",
        "| Stage | Provider | Model | Attempts | OK | Retried | Failed | Mean latency of OK calls (s) | Total wall time (s) |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for (stage, provider, model), items in sorted(groups.items()):
        ok = [r for r in items if r["status"] == "ok"]
        retried = sum(r["status"] == "retry" for r in items)
        failed = sum(r["status"] in ("failed", "partial") for r in items)
        latencies = [r["latency_s"] for r in ok if r.get("latency_s")]
        mean = f"{statistics.mean(latencies):.2f}" if latencies else "-"
        total = sum(r.get("latency_s") or 0 for r in items)
        lines.append(f"| {stage} | {provider} | `{model}` | {len(items)} | {len(ok)} | {retried} | {failed} | {mean} | {total:.0f} |")

    wasted = [r for r in rows if r["status"] != "ok"]
    lines += [
        "",
        f"{len(wasted)} of {len(rows)} attempts did not succeed. Most are the 503 and quota errors described in FAILURES.md F4 to F6.",
        "",
        "## GPU time (Kaggle, Tesla T4)",
        "",
        "| Stage | What | Outputs | GPU seconds generating | Whole job, push to download (s) | GPU minutes |",
        "|---|---|---|---|---|---|",
    ]
    gpu_total = 0.0
    for stage in ("smoke", "keyframes", "music", "video"):
        jobs = [r for r in rows if r["stage"] == stage and r["provider"] == "kaggle" and r["model"] in ("gpu-job", "gpu-check")]
        outputs = [r for r in rows if r["stage"] == stage and r["provider"] == "kaggle" and r["model"] not in ("gpu-job", "gpu-check") and r["status"] == "ok"]
        if not jobs:
            continue
        generating = sum(r.get("gpu_seconds") or 0 for r in outputs)
        session = sum((r.get("gpu_seconds") or r["params"].get("run_seconds") or 0) for r in jobs)
        wall = sum(r.get("latency_s") or 0 for r in jobs)
        gpu_total += session or generating
        lines.append(f"| {stage} | {len(jobs)} job(s) | {len(outputs)} | {generating:.0f} | {wall:.0f} | {(session or generating) / 60:.1f} |")
    per_image = [r["gpu_seconds"] for r in rows if r["stage"] == "keyframes" and r["model"] not in ("gpu-job",) and r["status"] == "ok" and r.get("gpu_seconds")]
    if per_image:
        lines += ["", f"Keyframes: {len(per_image)} images, mean {statistics.mean(per_image):.1f} s each on the GPU "
                      f"(min {min(per_image):.1f}, max {max(per_image):.1f})."]
    lines += [
        "",
        "The difference between GPU seconds and the whole job is queueing, container start and model download. "
        "That overhead, not the generation, is the real cost of a free GPU (EXPERIMENTS E10).",
        "",
        "## List-price equivalent",
        "",
        "What the same work would cost at published prices. Sources are in `pipeline/costs.py`.",
        "",
        "| Item | Measured quantity | List price | Equivalent (USD) |",
        "|---|---|---|---|",
    ]
    total_usd = 0.0
    for model, seconds in sorted(_audio_seconds_by_model().items()):
        price = SPEECH_USD_PER_10S.get(model)
        if price is None:
            continue
        usd = seconds / 10 * price
        total_usd += usd
        lines.append(f"| Narration kept, `{model}` | {seconds:.1f} s of audio | ${price} per 10 s | {usd:.4f} |")
    gpu_usd = gpu_total / 3600 * T4_USD_PER_HOUR
    total_usd += gpu_usd
    lines.append(f"| GPU sessions (images, music, video) | {gpu_total / 60:.1f} GPU minutes on one T4 | ${T4_USD_PER_HOUR} per hour | {gpu_usd:.4f} |")
    lines += [
        f"| **Total** | | | **{total_usd:.4f}** |",
        "",
        "Text calls (script drafts) are a fraction of a cent and are left out. Narration that was recorded and then "
        "discarded is not counted in the audio seconds above; the attempts are in the first table.",
        "",
        "## What the free tiers actually allowed",
        "",
        "Found by hitting them (FAILURES.md F5, F6, F8); these are not the numbers in the brief.",
        "",
        "| Service | Limit met |",
        "|---|---|",
        "| `gemini-3.8-flash` (text) | 5 requests a minute, 20 a day |",
        "| `gemini-3.8-flash-tts` | 10 requests in a rolling window; the error says when a slot frees up |",
        "| `gemini-3.8-flash-lite-tts` | 3 requests a minute, 10 in a rolling window |",
        "| Gemini image models | no free quota at all |",
        "| Cloudflare Workers AI | 10,000 neurons a day, shared by everything on the account |",
        "| Kaggle | two Tesla T4 (15 GB each), 20.9 GB disk, internet on; a job waits in a queue before it starts |",
        "",
        "## Frontier comparison",
        "",
        "Not run. No frontier image, video or music model was reachable without billing: the Gemini image models "
        "returned a quota error on the free key, and no organisation key was provided.",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    (ROOT / "COSTS.md").write_text(build(), encoding="utf-8")
    print("COSTS.md written")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
